// 组装小阿卡纳
const MINOR: TarotCard[] = [];
for (const suit of SUITS) {
  const specs = MINOR_SPEC[suit];
  const suitInfo = { wands: '权杖', cups: '圣杯', swords: '宝剑', pentacles: '星币' }[suit];
  for (const spec of specs) {
    const id = `${suit}_${String(spec.number).padStart(2, '0')}`;
    const element = SUIT_INFO[suit].element;
    MINOR.push(c(
      id, spec.name, `${suitInfo} ${spec.court || spec.number}`, 'minor',
      spec.kwU, spec.kwR, spec.mU, spec.mR,
      { suit, number: spec.number, court: spec.court, element },
    ));
  }
}

/** 全部 78 张牌 */
export const ALL_CARDS: TarotCard[] = [...MAJOR, ...MINOR];

/** 按 ID 查找 */
export function getCardById(id: string): TarotCard | undefined {
  return ALL_CARDS.find(c => c.id === id);
}

/** 按名称查找 */
export function getCardByName(name: string): TarotCard | undefined {
  return ALL_CARDS.find(c => c.name === name);
}

